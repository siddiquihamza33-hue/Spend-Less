// Builds lib/spendlens-core.js from packages/core + packages/banks.
// Run: pnpm build   (pnpm build --watch to rebuild on save)
import { build, context } from 'esbuild';

const options = {
  entryPoints: ['scripts/browser-entry.ts'],
  outfile: 'lib/spendlens-core.js',
  bundle: true,
  format: 'iife',
  globalName: 'SpendLensCore',
  platform: 'browser',
  target: ['chrome100', 'safari15', 'firefox100'],
  tsconfig: 'tsconfig.json',
  legalComments: 'none',
  banner: { js: '/* Spend Lens core — GENERATED by `pnpm build` from packages/core and packages/banks. Do not edit. */' },
  logLevel: 'info',
};

if (process.argv.includes('--watch')) {
  const ctx = await context(options);
  await ctx.watch();
} else {
  await build(options);
}
